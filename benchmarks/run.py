"""Run the 48 scope questions in benchmarks/scope_questions.cypher and write scope_questions.md.

    python -m benchmarks.run --url http://127.0.0.1:8094

Each query runs on the loaded graph; its answer is written beside the verdict of the raw-page
check (benchmarks/reference.py), which recomputes each answer from the catalog pages themselves.
Exit status is 0 only when every query runs, exactly the expected-empty questions return no rows
(Q26 and Q44 by their documented limit, Q46-Q48 by refusal), and no verdict is WRONG.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
CYPHER = HERE / "scope_questions.cypher"
REPORT = HERE / "scope_questions.md"
MUST_BE_EMPTY = {26, 44, 46, 47, 48}  # 26, 44: documented limits; 46-48: must be refused


def parse(path: Path = CYPHER) -> list[dict]:
    """[{n, question, cypher}] in file order; a block is '// Q<n> · question' then Cypher lines."""
    blocks, current = [], None
    for line in path.read_text(encoding="utf-8").splitlines():
        head = re.match(r"// Q(\d+) · (.*)", line)
        if head:
            current = {"n": int(head.group(1)), "question": head.group(2), "cypher": ""}
            blocks.append(current)
        elif current is not None and line.strip() and not line.startswith("//"):
            current["cypher"] += line.strip() + " "
        elif not line.strip():
            current = None
    return [dict(b, cypher=b["cypher"].strip()) for b in blocks]


def summary(columns, records, limit: int = 3) -> str:
    if not records:
        return "no rows"
    rows = ["; ".join(f"{c} {_short(v)}" for c, v in zip(columns, r, strict=False)) for r in records[:limit]]
    more = f" (+{len(records) - limit} more)" if len(records) > limit else ""
    return " | ".join(rows) + more


def _short(value) -> str:
    if isinstance(value, float):
        return f"{value:.3f}"
    text = ", ".join(map(str, value)) if isinstance(value, list) else str(value)
    return text if len(text) <= 60 else text[:57] + "…"


def run(url: str) -> list[dict]:
    from samyama import SamyamaClient
    client = SamyamaClient.connect(url)
    out = []
    for block in parse():
        began = time.perf_counter()
        result = client.query_readonly(block["cypher"])
        out.append({**block, "rows": len(result.records), "ms": 1000 * (time.perf_counter() - began),
                    "answer": summary(result.columns, result.records)})
    return out


def verdicts() -> dict[int, dict]:
    """The raw-page check's verdict per question (needs data/dbms_research and the parsed catalog)."""
    from benchmarks.reference import CATALOG, check_all
    from etl.loader import prepare
    return {r["question"]: r for r in check_all(prepare(json.loads(CATALOG.read_text(encoding="utf-8"))))}


def render(results: list[dict], checks: dict[int, dict], url: str) -> str:
    scope = (HERE / "scope.md").read_text(encoding="utf-8")
    text = dict(re.findall(r"^(\d+)\. (.+?)(?: \*\*\[|$)", scope, re.M))
    counts: dict[str, int] = {}
    for r in checks.values():
        counts[r["verdict"]] = counts.get(r["verdict"], 0) + 1
    lines = [
        "# Benchmark: the 48 scope questions", "",
        f"Generated by `python -m benchmarks.run --url {url}` from "
        "[scope_questions.cypher](scope_questions.cypher). Each question of [scope.md](scope.md) "
        "runs as Cypher on the loaded graph; the verdict comes from `python -m benchmarks.reference`, which "
        "recomputes the answer from the raw catalog pages with plain regexes (or, for computed links, "
        "checks it against the graph's own evidence).", "",
        "Verdicts: **correct** = equals the raw pages; **consistent** = agrees with the graph's evidence; "
        "**limited** = a documented partial answer whose limit holds; **refused** = a question the graph "
        "must refuse, and it returns nothing.", "",
        "**" + ", ".join(f"{v} {k}" for k, v in sorted(counts.items(), key=lambda kv: -kv[1]))
        + f" (of {len(checks)})**", "",
        "| # | Question | Verdict | Rows | ms | Answer on the graph |", "|---|---|---|---:|---:|---|",
    ]
    by_n = {r["n"]: r for r in results}
    for n in range(1, 49):
        question = text.get(str(n), "").replace("|", "/")
        verdict = checks.get(n, {}).get("verdict", "-")
        if n in by_n:
            r = by_n[n]
            lines.append(f"| {n} | {question} | {verdict} | {r['rows']} | {r['ms']:.0f} | "
                         f"{r['answer'].replace('|', '/')} |")
        else:
            lines.append(f"| {n} | {question} | {verdict} | – | – | no Cypher: needs vector search |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--url", default="http://127.0.0.1:8094")
    parser.add_argument("--report", type=Path, default=REPORT)
    args = parser.parse_args(argv)
    results = run(args.url)
    checks = verdicts()
    args.report.write_text(render(results, checks, args.url), encoding="utf-8")
    bad = [r["n"] for r in results if (r["n"] in MUST_BE_EMPTY) != (r["rows"] == 0)]
    wrong = [n for n, r in checks.items() if r["verdict"] == "WRONG"]
    for r in results:
        print(f"Q{r['n']:>2} {r['rows']:>4} rows {r['ms']:6.0f} ms  {r['answer'][:90]}")
    print(f"wrote {args.report}; unexpected row counts: {bad or 'none'}; WRONG verdicts: {wrong or 'none'}")
    return 0 if not bad and not wrong else 1


if __name__ == "__main__":
    sys.exit(main())
